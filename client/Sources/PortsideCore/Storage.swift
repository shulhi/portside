import Foundation
import Security

public struct ConfigurationStore: Sendable {
  public let fileURL: URL

  public init(fileURL: URL? = nil) {
    self.fileURL =
      fileURL
      ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
      .appendingPathComponent("Portside", isDirectory: true).appendingPathComponent(
        "configuration.json")
  }

  public func load() throws -> ClientConfiguration {
    guard FileManager.default.fileExists(atPath: fileURL.path) else { return ClientConfiguration() }
    return try JSONDecoder().decode(ClientConfiguration.self, from: Data(contentsOf: fileURL))
  }

  public func save(_ configuration: ClientConfiguration) throws {
    try FileManager.default.createDirectory(
      at: fileURL.deletingLastPathComponent(), withIntermediateDirectories: true)
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
    try encoder.encode(configuration).write(to: fileURL, options: [.atomic])
  }
}

public struct TokenVault: Sendable {
  private let service = "app.portside.server-token"
  public init() {}

  public static func validate(_ token: String) throws -> String {
    let value = token.trimmingCharacters(in: .whitespacesAndNewlines)
    guard value.utf8.count == 64,
      value.utf8.allSatisfy({
        (48...57).contains($0) || (65...70).contains($0) || (97...102).contains($0)
      })
    else { throw PortsideError.invalid("Paste the 64-character token generated by your server.") }
    return value
  }

  public func save(_ token: String, for serverID: UUID) throws {
    let value = try Self.validate(token)
    let query = baseQuery(serverID)
    let attributes: [String: Any] = [kSecValueData as String: Data(value.utf8)]
    var status = SecItemUpdate(query as CFDictionary, attributes as CFDictionary)
    if status == errSecItemNotFound {
      var item = query.merging(attributes) { _, new in new }
      item[kSecAttrAccessible as String] = kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly
      item[kSecAttrLabel as String] = "Portside server token"
      status = SecItemAdd(item as CFDictionary, nil)
    }
    guard status == errSecSuccess else { throw PortsideError.keychain(status) }
  }

  public func load(for serverID: UUID) throws -> String {
    var query = baseQuery(serverID)
    query[kSecReturnData as String] = true
    query[kSecMatchLimit as String] = kSecMatchLimitOne
    var result: CFTypeRef?
    let status = SecItemCopyMatching(query as CFDictionary, &result)
    guard status != errSecItemNotFound else {
      throw PortsideError.invalid("Add a token in this server's settings first.")
    }
    guard status == errSecSuccess, let data = result as? Data,
      let token = String(data: data, encoding: .utf8)
    else {
      throw PortsideError.keychain(status)
    }
    return token
  }

  public func delete(for serverID: UUID) throws {
    let status = SecItemDelete(baseQuery(serverID) as CFDictionary)
    guard status == errSecSuccess || status == errSecItemNotFound else {
      throw PortsideError.keychain(status)
    }
  }

  private func baseQuery(_ id: UUID) -> [String: Any] {
    [
      kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: service,
      kSecAttrAccount as String: id.uuidString,
    ]
  }
}
